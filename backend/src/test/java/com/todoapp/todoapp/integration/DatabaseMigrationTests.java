package com.todoapp.todoapp.integration;

import org.flywaydb.core.Flyway;
import org.flywaydb.core.api.FlywayException;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.condition.EnabledIfEnvironmentVariable;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.util.UUID;

import static org.junit.jupiter.api.Assertions.*;

@EnabledIfEnvironmentVariable(named = "TEST_DB_URL", matches = ".+")
class DatabaseMigrationTests {
    private Connection connection;
    private String schema;

    @BeforeEach
    void isolatedSchema() throws SQLException {
        String url = System.getenv("TEST_DB_URL");
        if (url == null || !url.matches("jdbc:postgresql://[^/]+/todo_integration")) {
            throw new IllegalStateException("Migration tests require the dedicated todo_integration database.");
        }
        connection = DriverManager.getConnection(url, System.getenv("TEST_DB_USERNAME"), System.getenv("TEST_DB_PASSWORD"));
        schema = "migration_test_" + UUID.randomUUID().toString().replace("-", "");
        execute("CREATE SCHEMA " + schema);
        connection.setSchema(schema);
    }

    @AfterEach
    void removeOnlyTestSchema() throws SQLException {
        if (connection == null) return;
        try {
            if (schema != null && schema.matches("migration_test_[a-f0-9]{32}")) {
                execute("DROP SCHEMA " + schema + " CASCADE");
            }
        } finally {
            connection.close();
        }
    }

    private Flyway flyway(boolean baseline) {
        return Flyway.configure().dataSource(System.getenv("TEST_DB_URL"), System.getenv("TEST_DB_USERNAME"), System.getenv("TEST_DB_PASSWORD"))
                .schemas(schema).defaultSchema(schema).baselineVersion("0").baselineOnMigrate(baseline)
                .cleanDisabled(true).locations("classpath:db/migration").load();
    }

    private void execute(String sql) throws SQLException {
        try (var statement = connection.createStatement()) { statement.execute(sql); }
    }

    private String scalar(String sql) throws SQLException {
        try (var statement = connection.createStatement(); var result = statement.executeQuery(sql)) {
            assertTrue(result.next());
            return result.getString(1);
        }
    }

    private void oldTables() throws SQLException {
        execute("CREATE TABLE users (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, username VARCHAR(255) NOT NULL UNIQUE, email VARCHAR(255) NOT NULL UNIQUE, password VARCHAR(255) NOT NULL)");
        execute("CREATE TABLE todos (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, title VARCHAR(255) NOT NULL, description VARCHAR(255), completed BOOLEAN NOT NULL, user_id BIGINT NOT NULL REFERENCES users(id))");
        execute("INSERT INTO users (username,email,password) VALUES ('legacy','legacy@example.test','unchanged-hash')");
        execute("INSERT INTO todos (title,description,completed,user_id) VALUES ('Original','Keep this',true,1)");
    }

    @Test
    void freshInstallCreatesTablesIndexesAndRunsOnlyOnce() throws SQLException {
        var flyway = flyway(false);
        assertEquals(3, flyway.migrate().migrationsExecuted);
        validateEntityMappings();
        flyway.validate();
        assertEquals(0, flyway.migrate().migrationsExecuted);
        assertEquals("3", scalar("SELECT count(*) FROM pg_indexes WHERE schemaname = '" + schema + "' AND indexname LIKE 'idx_todos_%'"));
        execute("INSERT INTO users (username,email,password) SELECT 'user' || n, 'user' || n || '@example.test', 'hash' FROM generate_series(1,10) n");
        execute("INSERT INTO todos (title,completed,user_id,due_date) SELECT 'Task ' || n, n % 2 = 0, (n % 10) + 1, DATE '2027-01-01' + n % 31 FROM generate_series(1,2000) n");
        execute("ANALYZE todos");
        String defaultPlan = explain("SELECT * FROM todos WHERE user_id=5 ORDER BY id DESC LIMIT 10");
        // PostgreSQL may prefer the primary-key index for this data distribution.
        assertTrue(defaultPlan.contains("Index"), defaultPlan);
        assertTrue(explain("SELECT * FROM todos WHERE user_id=5 ORDER BY CASE WHEN due_date IS NULL THEN 1 ELSE 0 END, due_date, id DESC LIMIT 10").contains("idx_todos_user_due_date"));
    }

    private String explain(String sql) throws SQLException {
        var plan = new StringBuilder();
        try (var statement = connection.createStatement(); var result = statement.executeQuery("EXPLAIN " + sql)) {
            while (result.next()) plan.append(result.getString(1)).append('\n');
        }
        return plan.toString();
    }

    private void validateEntityMappings() {
        var registry = new org.hibernate.boot.registry.StandardServiceRegistryBuilder()
                .applySetting("jakarta.persistence.jdbc.url", System.getenv("TEST_DB_URL"))
                .applySetting("jakarta.persistence.jdbc.user", System.getenv("TEST_DB_USERNAME"))
                .applySetting("jakarta.persistence.jdbc.password", System.getenv("TEST_DB_PASSWORD"))
                .applySetting("hibernate.default_schema", schema)
                .applySetting("hibernate.physical_naming_strategy", "org.hibernate.boot.model.naming.PhysicalNamingStrategySnakeCaseImpl")
                .applySetting("hibernate.hbm2ddl.auto", "validate")
                .build();
        try {
            try (var factory = new org.hibernate.boot.MetadataSources(registry)
                    .addAnnotatedClass(com.todoapp.todoapp.entity.User.class)
                    .addAnnotatedClass(com.todoapp.todoapp.entity.Todo.class)
                    .buildMetadata().buildSessionFactory()) {
                assertTrue(factory.isOpen());
            }
        } finally {
            org.hibernate.boot.registry.StandardServiceRegistryBuilder.destroy(registry);
        }
    }

    @Test
    void explicitBaselineUpgradesOldSchemaWithoutLosingRecords() throws SQLException {
        oldTables();
        assertEquals(3, flyway(true).migrate().migrationsExecuted);
        assertEquals("Original|Keep this|true|MEDIUM|Genel", scalar("SELECT title || '|' || description || '|' || completed || '|' || priority || '|' || category FROM todos WHERE id=1"));
        assertEquals("unchanged-hash", scalar("SELECT password FROM users WHERE id=1"));
        assertEquals("t", scalar("SELECT created_at IS NULL AND updated_at IS NULL AND due_date IS NULL FROM todos WHERE id=1"));
        execute("INSERT INTO todos (title,completed,user_id) VALUES ('Next',false,1)");
        assertEquals("2", scalar("SELECT id FROM todos WHERE title='Next'"));
    }

    @Test
    void currentSchemaKeepsExistingCategoriesPrioritiesAndDates() throws SQLException {
        oldTables();
        execute("ALTER TABLE todos ADD COLUMN priority VARCHAR(255), ADD COLUMN category VARCHAR(255), ADD COLUMN due_date DATE, ADD COLUMN created_at TIMESTAMP(6) WITH TIME ZONE, ADD COLUMN updated_at TIMESTAMP(6) WITH TIME ZONE");
        execute("UPDATE todos SET priority='HIGH',category='  Keep  ',due_date=DATE '2027-02-03',created_at=TIMESTAMPTZ '2020-01-01 12:00:00+00',updated_at=TIMESTAMPTZ '2021-01-01 12:00:00+00'");
        flyway(true).migrate();
        assertEquals("HIGH|  Keep  |2027-02-03", scalar("SELECT priority || '|' || category || '|' || due_date FROM todos WHERE id=1"));
        assertEquals("t", scalar("SELECT created_at=TIMESTAMPTZ '2020-01-01 12:00:00+00' AND updated_at=TIMESTAMPTZ '2021-01-01 12:00:00+00' FROM todos WHERE id=1"));
    }

    @Test
    void nonEmptySchemaRequiresExplicitBaseline() throws SQLException {
        oldTables();
        assertThrows(FlywayException.class, () -> flyway(false).migrate());
        assertEquals("Original", scalar("SELECT title FROM todos WHERE id=1"));
    }
}
